"""Lesson 16 — Alembic migration workflow reference (safe, no DB writes)."""


def main() -> None:
    steps = (
        ("Inspect current revision", "alembic current"),
        ("Inspect history", "alembic history"),
        ("Generate candidate migration", 'alembic revision --autogenerate -m "add artwork slug"'),
        ("Review generated upgrade/downgrade", "Inspect for drops, renames, constraints and backfills"),
        ("Apply all pending revisions", "alembic upgrade head"),
        ("Check metadata/schema differences", "alembic check"),
        ("Reverse one revision if appropriate", "alembic downgrade -1"),
    )
    print("Lesson 16: Alembic refresher (no database operations performed)\n")
    for index, (purpose, command) in enumerate(steps, start=1):
        print(f"{index}. {purpose}: {command}")
    print("\nRemember: ORM model changes do not automatically change the database.")
    print("Autogenerated migrations are proposals: review them before applying.")


if __name__ == "__main__":
    main()
